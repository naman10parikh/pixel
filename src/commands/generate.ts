// src/commands/generate.ts — `pixel generate "<prompt>"` (B9 / JOB 5, v0 first-pass draft).
// v0 is the stack-aligned generator (React/Tailwind/shadcn). Programmatic via the v0 Platform
// API + `v0-sdk` (v0.chats.create). EVERYTHING it emits is an UNTRUSTED DRAFT (O7, ~40-45%
// vulnerable) and is tagged "DRAFT — must pass `pixel audit`". The R2 fallback (PLAN §13): with
// no V0_API_KEY or no network, generation is SKIPPED with a note (exit 0, not a failure) — the
// HARD gate (`pixel audit` / impeccable) is keyless, so pixel's value (taste+structure) does not
// depend on v0. v0-sdk is imported DYNAMICALLY only when a key is present, so it is not a forced
// dependency of the CLI skeleton (Karpathy: no deps beyond what's needed). Logs the run.

import chalk from "chalk";
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { logRun, startTimer } from "../lib/logger.js";
import type { GateResult } from "../lib/logger.js";

const DRAFT_TAG = "DRAFT — generated by v0, UNTRUSTED. Must pass `pixel audit` before merge (O7).";

/** Read the v0 key under the confirmed-or-candidate env names (GAPS §6 — name TBD). */
function v0Key(): string | undefined {
  return process.env.V0_API_KEY ?? process.env.V0_TOKEN ?? process.env.VERCEL_V0_API_KEY;
}

export async function runGenerate(
  prompt: string,
  opts: { model: string; out?: string },
): Promise<number> {
  const elapsed = startTimer();
  const gates: GateResult[] = [];

  if (!prompt || prompt.trim().length === 0) {
    console.error(chalk.red("pixel generate: empty prompt — provide what to generate."));
    logRun({ cmd: "generate", model: null, duration_ms: elapsed(), tool_calls: 0, gate_results: [], exit: 2 });
    return 2;
  }

  const key = v0Key();
  if (!key) {
    // R2 fallback — no key → SKIP, not fail. The acceptance test proves taste+structure via the
    // keyless scaffold path; v0 only accelerates. This is the path CI must prove works tokenlessly.
    console.error(chalk.yellow("pixel generate: no V0_API_KEY in env — generation skipped (R2 fallback)."));
    console.error(chalk.dim("  v0 ACCELERATES; it is not required. Run `pixel scaffold` for the keyless structure path,"));
    console.error(chalk.dim("  and `pixel audit` (keyless impeccable) for the taste gate. Set V0_API_KEY to enable v0."));
    gates.push({ gate: "v0-generate", pass: null, detail: "skipped — no V0_API_KEY (R2)" });
    logRun({ cmd: "generate", model: null, duration_ms: elapsed(), tool_calls: 0, gate_results: gates, exit: 0, skipped: "no-v0-key" });
    return 0;
  }

  // Key present → attempt the v0 Platform API. v0-sdk is imported dynamically so it is only
  // required when actually generating. A missing package / network error degrades to R2.
  let draftPath: string | null = null;
  try {
    // Non-literal specifier so `tsc` does not require v0-sdk to be installed at build time —
    // it is an OPTIONAL dependency, imported only when a V0_API_KEY is present (R2 otherwise).
    const v0Module = "v0-sdk";
    const mod = (await import(v0Module)) as unknown as {
      v0?: { chats: { create: (a: { message: string; system?: string }) => Promise<unknown> } };
      createClient?: (o: { apiKey: string }) => { chats: { create: (a: { message: string; system?: string }) => Promise<unknown> } };
    };
    const client = mod.createClient ? mod.createClient({ apiKey: key }) : mod.v0;
    if (!client) throw new Error("v0-sdk did not export a usable client");

    console.log(chalk.dim(`  calling v0 (${opts.model}) …`));
    const result = await client.chats.create({
      message: prompt,
      system:
        "Generate React/Tailwind v4/shadcn for a Next.js 16 app. Warm-black #141312, Instrument Serif + Poppins, ONE amber OKLCH accent, bento layout. No purple, no Inter-for-everything, no cards-in-cards.",
    });

    const out = opts.out ?? join(process.cwd(), "pixel-draft");
    if (!existsSync(out)) mkdirSync(out, { recursive: true });
    draftPath = join(out, "v0-draft.json");
    writeFileSync(draftPath, JSON.stringify({ tag: DRAFT_TAG, prompt, model: opts.model, result }, null, 2), "utf8");

    console.log(chalk.green("pixel generate: draft written →"), draftPath);
    console.log(chalk.yellow(`  ⚠ ${DRAFT_TAG}`));
    gates.push({ gate: "v0-generate", pass: true, detail: "draft emitted (UNTRUSTED)" });
    logRun({ cmd: "generate", model: opts.model, duration_ms: elapsed(), tool_calls: 1, gate_results: gates, exit: 0, out: draftPath });
    return 0;
  } catch (err) {
    // Network/SDK failure → R2 fallback, not a hard error (v0 is an accelerant).
    console.error(chalk.yellow("pixel generate: v0 call failed — falling back to scaffold-only (R2)."), chalk.dim(err instanceof Error ? err.message : String(err)));
    gates.push({ gate: "v0-generate", pass: null, detail: "v0 unreachable — R2 fallback" });
    logRun({ cmd: "generate", model: opts.model, duration_ms: elapsed(), tool_calls: 1, gate_results: gates, exit: 0, skipped: "v0-unreachable" });
    return 0;
  }
}
